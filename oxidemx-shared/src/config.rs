    fn missing_config_defaults_to_current_schema() {
        let cfg = AppConfig::load_from(std::path::Path::new(
            "/nonexistent/oxidemx-test/config.json",
        ))
        .unwrap();
        assert_eq!(cfg.schema_version, CURRENT_SCHEMA_VERSION);
    }
