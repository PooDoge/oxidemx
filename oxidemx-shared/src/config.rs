/// One radial slice. Position in the parent vec determines its angular
/// placement (8 slices = 45° each, slot 0 = top, clockwise).
///
/// Fields beyond label / type / command / color / icon are optional so
/// older config.json files (which don't have submenu support yet) still
/// deserialize cleanly.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct Slice {
    /// Stable id for the slice. Optional — generated by the editor when
    /// missing. Used to attach hover analytics, per-app overrides, etc.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub action_id: Option<String>,

    pub label: String,

    #[serde(rename = "type", default)]
    pub kind: ActionKind,

    /// Shell command for `Exec`, macro id for `Macro`, host index ("0".."2")
    /// for `EasySwitch`, ignored for other kinds.
    #[serde(default)]
    pub command: String,

    /// Slice highlight colour. The string is a key into the active theme's
    /// palette (e.g. "green", "sapphire", "teal"); the overlay resolves it
    /// to a concrete RGBA at render time.
    #[serde(default)]
    pub color: String,

    /// freedesktop symbolic icon name (preferred), an absolute path to a
    /// custom SVG/PNG, or one of the legacy internal ids handled by the
    /// hand-drawn renderer.
    #[serde(default)]
    pub icon: String,

    /// When true, render the icon at its original colours instead of
    /// tinting it to the slice colour. Useful for full-colour app
    /// icons (Firefox, Chromium, GIMP, …) where the brand identity
    /// matters; symbolic icons should leave this `false` so they
    /// pick up the slice colour as a monochrome highlight.
    #[serde(default, skip_serializing_if = "is_false")]
    pub icon_untinted: bool,

    /// Optional longer-form notes / tooltip text for the slice.
    /// Renders as a smaller subtitle under the slice label inside
    /// the overlay's centre puck while the slice is hovered — use
    /// it for "deploy to staging via shipit (don't run on prod!)"
    /// type reminders. Empty string = no subtitle (the puck just
    /// shows the label, same as before this field existed).
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub description: String,

    /// Sub-items shown when this slice is hovered with `kind = Submenu`.
    /// Empty for non-submenu slices.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub submenu: Vec<Slice>,

    /// Optional visibility predicate. Slices whose predicate evaluates
    /// to `false` are skipped at render time — their slot stays empty
    /// rather than being filled by the next slice (so the menu's
    /// muscle-memory layout is preserved). `None` means always
    /// visible. See the `conditions` module for the variants.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub visible_if: Option<Condition>,

    /// Live-data binding for `ActionKind::Widget` slices. `None` on
    /// every other kind (and on widget slices hand-edited without a
    /// source — those render the stub placeholder).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub widget: Option<WidgetConfig>,

    /// Adjustment target for `ActionKind::Dial` slices. `None` on
    /// every other kind.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub dial: Option<DialKind>,
}

/// Data binding for a live widget wedge.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
pub struct WidgetConfig {
    pub source: WidgetSource,
    /// Optional format override for the big value (e.g. "{}%").
    /// `None` = the source's default formatting. Built-ins only.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub format: Option<String>,
    /// Where the options card writes (spec §6) — and which layers apply
    /// on read: resolution merges defaults ← global, then the instance
    /// bag on top only when this is `Instance`. Under `Global` the
    /// instance bag is ignored (kept on disk for toggling back).
    #[serde(default)]
    pub scope: WidgetScope,
    /// Key into `AppConfig::widgets.instances` — `<page-slug>.slot<N>`,
    /// assigned by the settings editor when a custom widget is placed.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub instance_key: Option<String>,
}

/// Which level of the two-bag widget settings store an options card
/// writes to — and whether the instance bag participates in reads
/// (it does only under `Instance`; spec §6).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum WidgetScope {
    #[default]
    Instance,
    Global,
}

/// Which live data feed a widget wedge renders.
///
/// NOTE: no longer `Copy` — `Custom` carries the installed widget id.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum WidgetSource {
    Weather,
    Cpu,
    Memory,
    Network,
    Disk,
    TasksDue,
    MouseBattery,
    /// Installed plugin widget, by manifest id (e.g. "weather2").
    Custom(String),
}

